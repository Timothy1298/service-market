import { apiRequest } from '../../../services/apiClient'

export const customerPortalApi = {
  dashboard: () => apiRequest<any>('/customer-portal/dashboard'),
  profile: () => apiRequest<any>('/customer-portal/profile'),
  updateProfile: (body: unknown) => apiRequest<any>('/customer-portal/profile', { method: 'PATCH', body: JSON.stringify(body) }),
  categories: () => apiRequest<any>('/marketplace/categories'),
  providers: (query = '') => apiRequest<any>(`/marketplace/providers${query ? `?${query}` : ''}`),
  provider: (id: string) => apiRequest<any>(`/marketplace/providers/${id}`),
  requests: () => apiRequest<any>('/requests'),
  createRequest: (body: unknown) => apiRequest<any>('/requests', { method: 'POST', body: JSON.stringify(body) }),
  quotations: () => apiRequest<any>('/customer-portal/quotations'),
  respond: (id: string, decision: 'ACCEPTED' | 'REJECTED') => apiRequest<any>(`/customer-portal/quotations/${id}/respond`, { method: 'POST', body: JSON.stringify({ decision }) }),
  jobs: () => apiRequest<any>('/customer-portal/jobs'),
  invoices: () => apiRequest<any>('/customer-portal/invoices'),
  favorites: () => apiRequest<any>('/customer-portal/favorites'),
  saveFavorite: (id: string) => apiRequest<any>(`/customer-portal/favorites/${id}`, { method: 'PUT' }),
  removeFavorite: (id: string) => apiRequest<any>(`/customer-portal/favorites/${id}`, { method: 'DELETE' }),
  mpesa: (id: string, phoneNumber: string, amount: number) => apiRequest<any>(`/invoices/${id}/mpesa/initiate`, { method: 'POST', body: JSON.stringify({ phoneNumber, amount }) }),
  mpesaAttempts: (id: string) => apiRequest<any>(`/customer-portal/invoices/${id}/mpesa/attempts`),
  reviews: () => apiRequest<any>('/customer-portal/reviews'),
  notifications: () => apiRequest<any>('/notifications'),
  conversations: () => apiRequest<any>('/customer-portal/conversations'),
  openConversation: (body: unknown) => apiRequest<any>('/customer-portal/conversations', { method: 'POST', body: JSON.stringify(body) }),
  messages: (id: string) => apiRequest<any>(`/customer-conversations/${id}/messages`),
  sendMessage: (id: string, body: string) => apiRequest<any>(`/customer-conversations/${id}/messages`, { method: 'POST', body: JSON.stringify({ body }) }),
  request: (id: string) => apiRequest<any>(`/requests/${id}`),
  cancelRequest: (id: string) => apiRequest<any>(`/requests/${id}`, { method: 'PATCH', body: JSON.stringify({ status: 'CANCELLED' }) }),
  review: (id: string, body: unknown) => apiRequest<any>(`/customer-portal/jobs/${id}/review`, { method: 'POST', body: JSON.stringify(body) }),
}
